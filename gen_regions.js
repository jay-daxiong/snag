// 直辖市/主要城市的区县已在上方；其余自动补 ['市辖区']
function build() {
  var provinces = PROVINCES.map(function (p) {
    return { code: p[0], name: p[1], lat: p[2], lon: p[3] };
  });
  var cities = CITIES.map(function (c) {
    return { code: c[0], name: c[1], provinceCode: c[2], lat: c[3], lon: c[4] };
  });
  var provMap = {}; provinces.forEach(function (p) { provMap[p.code] = p; });
  var cityMap = {}; cities.forEach(function (c) { cityMap[c.code] = c; });

  // 反向索引：city -> counties（没有则市辖区）
  var counties = {};
  Object.keys(COUNTIES).forEach(function (k) {
    counties[k] = COUNTIES[k].map(function (a) { return { name: a[0], lat: a[1], lon: a[2] }; });
  });
  cities.forEach(function (c) {
    if (!counties[c.code]) counties[c.code] = [{ name: '市辖区', lat: c.lat, lon: c.lon }];
  });

  return { provinces: provinces, cities: cities, counties: counties, provMap: provMap, cityMap: cityMap };
}

var DATA = build();

function haversineKm(lat1, lon1, lat2, lon2) {
  var R = 6371, dLat = (lat2 - lat1) * Math.PI / 180, dLon = (lon2 - lon1) * Math.PI / 180;
  var a = Math.sin(dLat / 2) * Math.sin(dLat / 2) + Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) * Math.sin(dLon / 2) * Math.sin(dLon / 2);
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

// 反查：经纬度 -> {province, city, county?}
function reverseGeocode(lat, lon) {
  var bestCity = null, bestD = Infinity;
  DATA.cities.forEach(function (c) {
    var d = haversineKm(lat, lon, c.lat, c.lon);
    if (d < bestD) { bestD = d; bestCity = c; }
  });
  var province = DATA.provMap[bestCity.provinceCode];
  var county = null, countyD = Infinity;
  (DATA.counties[bestCity.code] || []).forEach(function (co) {
    var d = haversineKm(lat, lon, co.lat, co.lon);
    if (d < countyD) { countyD = d; county = co; }
  });
  // 仅当县坐标距离合理（< 该市最大半径估计）才采信
  if (county && countyD > 80) county = null;
  return {
    province: province, city: bestCity, county: county,
    cityDistanceKm: bestD, accuracyNote: bestD < 60 ? '市级精准' : '已就近归属到最近地级市'
  };
}

